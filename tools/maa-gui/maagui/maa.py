# ---------------------------------------------------------------------------
# Paths / versions
# ---------------------------------------------------------------------------

_CONFIG_DIR = Path(os.environ.get("MAA_CONFIG_DIR", Path.home() / ".config" / "maa"))


def maa_binary() -> str | None:
    return shutil.which("maa")


def _dir(kind: str) -> Path:
    """Resolve a maa-cli directory (`maa dir <kind>`), falling back to defaults."""
    bin_ = maa_binary()
    if bin_:
        try:
            out = subprocess.run(
                [bin_, "dir", kind], capture_output=True, text=True, timeout=10
            )
            if out.returncode == 0:
                return Path(out.stdout.strip())
        except (OSError, subprocess.TimeoutExpired):
            pass
    if kind == "config":
        return _CONFIG_DIR
    if kind == "log":
        return Path.home() / ".local" / "state" / "maa" / "debug"
    return Path.home() / ".cache" / "maa"


def config_dir() -> Path:
    return _dir("config")


def dir_data() -> Path:
    return _dir("data")


def profiles_dir() -> Path:
    return config_dir() / "profiles"


def tasks_dir() -> Path:
    return config_dir() / "tasks"


def log_dir() -> Path:
    return _dir("log")


def versions() -> tuple[str, str]:
    """Return (maa-cli version, MaaCore version), or ("", "") if unavailable."""
    bin_ = maa_binary()
    if not bin_:
        return ("", "")
    try:
        out = subprocess.run([bin_, "version"], capture_output=True, text=True, timeout=15)
        if out.returncode != 0:
            return ("", "")
        cli = core = ""
        for line in out.stdout.splitlines():
            if line.startswith("maa-cli"):
                cli = line.split()[-1]
            elif line.startswith("MaaCore"):
                core = line.split()[-1]
        return (cli, core)
    except (OSError, subprocess.TimeoutExpired):
        return ("", "")


