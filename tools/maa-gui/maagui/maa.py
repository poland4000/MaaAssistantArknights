def check_device(
    preset: str = "", address: str = "", adb_path: str = "", window_name: str = ""
) -> tuple[bool, str]:
    """Check whether the device is reachable. Returns (ok, detail)."""
    try:
        if preset.lower() == "window":
            name = window_name or "Arknights"
            try:
                r = subprocess.run(
                    ["xdotool", "search", "--name", name],
                    capture_output=True, text=True, timeout=10,
                )
            except FileNotFoundError:
                return False, "xdotool not found (install xdotool)"
            wins = [ln for ln in r.stdout.splitlines() if ln.strip()]
            if not wins:
                return False, f'no X11 window titled "{name}"'
            return True, f'window "{name}" found ({(len(wins))} match(es))'
        if preset.lower() == "waydroid":
            r = subprocess.run(
                ["waydroid", "status"], capture_output=True, text=True, timeout=10
            )
            if r.returncode == 0:
                for line in r.stdout.splitlines():
                    if "Session:" in line and "RUNNING" in line.upper():
                        return True, "Waydroid session running"
                return False, r.stdout.strip() or "Waydroid session not running"
            return False, (r.stderr or r.stdout).strip() or "waydroid status failed"

        adb = adb_path or shutil.which("adb") or "adb"
        r = subprocess.run(
            [adb, "devices"], capture_output=True, text=True, timeout=10
        )
        if r.returncode != 0:
            return False, (r.stderr or r.stdout).strip() or "adb not found"
        lines = [ln for ln in r.stdout.splitlines()[1:] if ln.strip()]
        if not lines:
            return False, "no adb devices"
        target = address or "emulator-5554"
        for ln in lines:
            dev, _, state = ln.partition("\t")
            if dev == target:
                return state.strip() == "device", f"{dev} [{state.strip()}]"
        return True, f"{len(lines)} device(s), {target} not listed"
    except (OSError, subprocess.TimeoutExpired) as e:
        return False, str(e)


def run_sync(args: list[str], timeout: int = 120) -> subprocess.CompletedProcess:
    """Run a maa-cli subcommand synchronously (used for quick actions)."""
    return subprocess.run(
        [maa_binary()] + args, capture_output=True, text=True, timeout=timeout
    )


_OPERBOX_RE = re.compile(r'SubTaskExtraInfo (\{.*\})')
_OPERBOX_TASKCHAIN_RE = re.compile(r'"taskchain"\s*:\s*"OperBox"')


def latest_operbox_message() -> dict | None:
    """Parse the newest OperBox callback JSON from MaaCore's asst.log.

    MaaCore logs the full `SubTaskExtraInfo` message (including the operator
    roster) as one compact JSON line — far more reliable than scraping the
    pretty-printed stream from maa-cli's logger.
    """
    path = log_dir() / "asst.log"
    if not path.is_file():
        return None
    try:
        size = path.stat().st_size
        with open(path, "rb") as f:
            f.seek(max(0, size - 6 * 1024 * 1024))  # tail ~6 MB
            tail = f.read().decode("utf-8", errors="replace")
    except OSError:
        return None
    for line in reversed(tail.splitlines()):
        if not _OPERBOX_TASKCHAIN_RE.search(line):
            continue
        m = _OPERBOX_RE.search(line)
        if not m:
            continue
        try:
            msg = json.loads(m.group(1))
        except json.JSONDecodeError:
            continue
        if msg.get("taskchain") == "OperBox":
            return msg
    return None


