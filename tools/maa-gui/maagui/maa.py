def list_profiles() -> list[str]:
    d = profiles_dir()
    if not d.is_dir():
        return []
    return sorted(p.stem for p in d.iterdir() if p.suffix in (".toml", ".json", ".yaml", ".yml"))


def ensure_default_profile() -> str:
    """Create a ``default`` profile on first run so the GUI never starts with
    an empty profile list. Returns the name of the profile to select."""
    if not list_profiles():
        write_profile("default", {"connection": {"preset": "", "window_name": "Arknights"}})
        return "default"
    return ""


def read_profile(name: str) -> dict:
    path = profiles_dir() / f"{name}.toml"
    if not path.is_file():
        # try other formats
        for ext in (".json", ".yaml", ".yml"):
            p = profiles_dir() / f"{name}{ext}"
            if p.is_file():
                path = p
                break
    if not path.is_file():
        return {}
    with open(path, "rb") as f:
        try:
            return tomllib.load(f)
        except tomllib.TOMLDecodeError:
            return {}


def _profile_path(name: str) -> Path:
    return profiles_dir() / f"{name}.toml"


def _fmt_scalar(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return f'"{value}"'


_SCALAR_RE = re.compile(r'^(\s*[A-Za-z_][A-Za-z0-9_]*\s*=\s*)(.+?)(\s*(?:#.*)?)$')


def set_profile_fields(name: str, values: dict[str, str | int | float | bool]) -> None:
    """Update scalar fields of a profile in place, preserving comments.

    ``values`` uses ``"section.key"`` as keys. Empty/None values remove the
    line (so an empty address falls back to maa-cli auto-detection); missing
    keys are appended to the end of their section.
    """
    profiles_dir().mkdir(parents=True, exist_ok=True)
    path = _profile_path(name)
    text = path.read_text() if path.is_file() else ""

    # map section -> {key: line_index}
    section_lines: dict[str, list[int]] = {}
    current: str | None = None
    lines = text.splitlines()
    for i, line in enumerate(lines):
        m = re.match(r"^\s*\[([^\]]+)\]\s*$", line)
        if m:
            current = m.group(1).strip()
            section_lines.setdefault(current, []).append(i)
            continue
        if current and line.strip() and not line.strip().startswith("#"):
            section_lines.setdefault(current, []).append(i)

    for key, value in values.items():
        section, _, field = key.partition(".")
        replaced = False
        for i in section_lines.get(section, []):
            line = lines[i]
            m = re.match(rf"^\s*({re.escape(field)}\s*=\s*)(.+?)(\s*(?:#.*)?)$", line)
            if m and not line.lstrip().startswith("["):
                if value is None or value == "":
                    lines[i] = ""  # remove the line
                else:
                    lines[i] = f"{m.group(1)}{_fmt_scalar(value)}{m.group(3)}"
                replaced = True
                break
        if replaced or value is None or value == "":
            continue
        # key not present: insert right after the section header
        if section in section_lines and section_lines[section]:
            anchor = section_lines[section][0]
        else:
            # new section: append at end of file
            if lines and lines[-1].strip():
                lines.append("")
            lines.append(f"[{section}]")
            anchor = len(lines) - 1
            section_lines[section] = [anchor]
        lines.insert(anchor + 1, f"{field} = {_fmt_scalar(value)}")
        section_lines[section] = [i + 1 if i > anchor else i for i in section_lines[section]]

    # drop blank lines that were emptied out
    out = [ln for ln in lines if ln != "" or False]
    out = []
    blank = False
    for ln in lines:
        if ln.strip() == "":
            if blank:
                continue
            blank = True
        else:
            blank = False
        out.append(ln)
    path.write_text("\n".join(out).rstrip() + "\n")


def write_profile(name: str, data: dict) -> None:
    """Full overwrite (used by 'duplicate profile')."""
    profiles_dir().mkdir(parents=True, exist_ok=True)
    (_profile_path(name)).write_text(_dumps(data) + "\n")


def delete_profile(name: str) -> None:
    path = _profile_path(name)
    if path.is_file():
        path.unlink()


def duplicate_profile(src: str, dst: str) -> None:
    profiles_dir().mkdir(parents=True, exist_ok=True)
    src_path = _profile_path(src)
    dst_path = _profile_path(dst)
    if src_path.is_file():
        dst_path.write_text(src_path.read_text())


