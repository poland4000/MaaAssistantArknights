"""maa-cli integration layer: paths, versions, profile/task CRUD, device checks.

Everything the GUI knows about maa-cli lives here, so the pages stay thin.
Profile files are user-authored TOML that may contain comments — when the GUI
edits a profile it updates scalar `key = value` lines *in place* (preserving
comments and unknown fields), and only appends keys that don't exist yet.
Task files, on the other hand, are fully generated by the GUI (names prefixed
``__gui_``) and serialized with the small TOML writer at the bottom of this
module (``tomli_w`` is not guaranteed to be installed).
"""

from __future__ import annotations

