# ---------------------------------------------------------------------------
# Task file generation
# ---------------------------------------------------------------------------

def _toml_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        # escape backslash, quote, control chars
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    if isinstance(v, list):
        return "[" + ", ".join(_toml_value(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{_toml_key(k)} = {_toml_value(x)}" for k, x in v.items()) + " }"
    return str(v)


def _toml_key(k: str) -> str:
    if re.fullmatch(r"[A-Za-z0-9_-]+", k):
        return k
    return _toml_value(k)


def task_file_text(subtasks: list[tuple[str, str, dict]], header: str = "") -> str:
    """Serialize subtasks [(name, type, params)] into a maa-cli task file."""
    parts = []
    if header:
        parts.append(header.rstrip())
    for i, (name, ttype, params) in enumerate(subtasks):
        if parts and parts[-1].strip():
            parts.append("")
        parts.append("[[tasks]]")
        if name:
            parts.append(f"name = {_toml_value(name)}")
        parts.append(f"type = {_toml_value(ttype)}")
        if params:
            parts.append("")
            parts.append("[tasks.params]")
            for k, v in params.items():
                if v is None or v == "":
                    continue  # skip empty params (empty arrays are kept —
                    # MaaCore requires e.g. Recruit's select/confirm arrays)
                parts.append(f"{_toml_key(k)} = {_toml_value(v)}")
    return "\n".join(parts).rstrip() + "\n"


def _dumps(data: dict) -> str:
    """Small TOML writer for flat config files (profiles)."""
    out = []
    for section, fields in data.items():
        out.append(f"[{section}]")
        for k, v in fields.items():
            if v is None or v == "":
                continue
            out.append(f"{k} = {_toml_value(v)}")
        out.append("")
    return "\n".join(out).rstrip()


